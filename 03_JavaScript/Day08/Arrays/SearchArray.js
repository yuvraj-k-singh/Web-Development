let arr = [10,20,20,20,20,6,5,8,9,3,54,66,45];
console.log(`Original Array: ${arr}`);

//1. Includes Method
console.log(`\n1. Include: ${arr.includes(20)}`);

//2. IndexOf Method
console.log(`\n2. IndexOf: ${arr.indexOf(-20)}`);

//3. Last IndexOf Method
console.log(`\n3. Last IndexOf: ${arr.lastIndexOf(20)}`);