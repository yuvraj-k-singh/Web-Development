const dropdown = document.querySelectorAll(".dropdown select");
const form = document.querySelector("form");

for(let list of dropdown){
    for(let country in countryList){
        let option = document.createElement("option");
        if(list.name === "from" && country === "USD"){
            option.selected = "selected";
        }else if(list.name === "to" && country === "INR"){
            option.selected = "selected";
        }
        option.value = country;
        option.textContent = country;
        list.append(option);
    }

    list.addEventListener('change', (e)=>{
        updateFlag(e.target);
    });
}

function updateFlag(country){
    let code = country.value;
    let img = country.parentElement.querySelector("img");
    img.src = `https://flagsapi.com/${countryList[code]}/flat/64.png`;
}

const input = document.querySelector("input");

input.addEventListener("input", () => {
    input.value = input.value.replace(/[^0-9.]/g, "");
});

const from = document.querySelector(".from select");
const to = document.querySelector(".to select");
const BASEURL = "https://api.frankfurter.dev/v2/rate";

form.addEventListener('submit', async (e)=>{
    e.preventDefault();

    const amount = document.querySelector("input").value.trim();
    if (amount === "" || Number(amount) <= 0 || isNaN(amount)){
        alert("Enter a valid amount!");
        return;
    }

    const URL = `${BASEURL}/${from.value}/${to.value}`;
    try{
        let response = await fetch(URL);
        if(!response.ok){
            throw new Error("Failed to fetch exchange rate");
        }
        let data = await response.json();
        let exchange = (amount * data.rate).toFixed(2);
        
        const msg = document.querySelector("#msg");
        msg.textContent = `${amount} ${from.value} = ${exchange} ${to.value}`;
    }catch(error){
        console.log(error);
    }
    //form.reset();
});

